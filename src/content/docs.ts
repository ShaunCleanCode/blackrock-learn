function navDocs(items: DocNavItem[]): Extract<DocNavItem, { type: "doc" }>[] {
  const out: Extract<DocNavItem, { type: "doc" }>[] = [];
  for (const item of items) {
    if (item.type === "doc") out.push(item);
    else out.push(...navDocs(item.items));
  }
  return out;
}

export function allDocs(): DocPage[] {
  const existing = new Map(pages.map((p) => [p.slug, p] as const));
  const merged: DocPage[] = [];

  for (const nav of navDocs(navTree)) {
    const found = existing.get(nav.slug);
    if (found) merged.push(found);
    else
      merged.push({
        slug: nav.slug,
        title: nav.title,
        blocks: [
          { type: "h1", text: nav.title },
          {
            type: "p",
            text: "이 섹션은 번역/요약 원고를 받는 대로 채워집니다. (현재는 레이아웃 확인을 위한 준비중 페이지입니다.)",
          },
        ],
      });
  }

  return merged;
}

export function getDocBySlug(slug: string): DocPage | undefined {
  const existing = pages.find((p) => p.slug === slug);
  if (existing) return existing;

  const nav = navDocs(navTree).find((d) => d.slug === slug);
  if (!nav) return undefined;

  return {
    slug: nav.slug,
    title: nav.title,
    blocks: [
      { type: "h1", text: nav.title },
      {
        type: "p",
        text: "이 섹션은 번역/요약 원고를 받는 대로 채워집니다. (현재는 레이아웃 확인을 위한 준비중 페이지입니다.)",
      },
    ],
  };
}

